"""PostgreSQL access: connections, schema and the one-time import of the legacy SQLite file."""

import json
import logging
import os
import sqlite3
import time
from contextlib import closing
from datetime import UTC, datetime
from pathlib import Path

import psycopg
from psycopg.rows import dict_row

LEGACY_FLAG = "sqlite_imported"
IMPORT_LOCK = 7001

SCHEMA = """
CREATE TABLE IF NOT EXISTS metadata (
    key TEXT PRIMARY KEY,
    value JSONB NOT NULL
);
CREATE TABLE IF NOT EXISTS statements (
    period_end DATE PRIMARY KEY,
    period_start DATE NOT NULL,
    row_json JSONB NOT NULL,
    pdf BYTEA,
    sha256 TEXT UNIQUE
);
CREATE TABLE IF NOT EXISTS events (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    title TEXT NOT NULL,
    category TEXT NOT NULL,
    notes TEXT NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS weather (
    location_key TEXT NOT NULL,
    day DATE NOT NULL,
    mean DOUBLE PRECISION NOT NULL,
    low DOUBLE PRECISION NOT NULL,
    high DOUBLE PRECISION NOT NULL,
    fetched_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (location_key, day)
);
"""


def connect():
    """Open a connection; DATABASE_URL wins, otherwise the standard PG* variables apply."""
    return psycopg.connect(
        os.environ.get("DATABASE_URL", ""), row_factory=dict_row, connect_timeout=10
    )


def wait_for_database(timeout=60):
    deadline = time.monotonic() + timeout
    while True:
        try:
            with connect() as db:
                db.execute("SELECT 1")
            return
        except psycopg.OperationalError:
            if time.monotonic() > deadline:
                raise
            logging.info("Waiting for PostgreSQL…")
            time.sleep(2)


def create_schema(db):
    db.execute(SCHEMA)


def import_legacy_sqlite(db, path):
    """Copy a legacy statements.sqlite into PostgreSQL once; the source file is never modified."""
    path = Path(path)
    if not path.exists():
        return None
    if db.execute("SELECT 1 FROM metadata WHERE key=%s", (LEGACY_FLAG,)).fetchone():
        return None
    db.execute("SELECT pg_advisory_xact_lock(%s)", (IMPORT_LOCK,))
    counts = {}
    with closing(sqlite3.connect(f"file:{path}?mode=ro", uri=True)) as source:
        source.row_factory = sqlite3.Row
        tables = {
            r["name"] for r in source.execute("SELECT name FROM sqlite_master WHERE type='table'")
        }

        def copy(table, statement, columns):
            if table not in tables:
                counts[table] = 0
                return
            rows = [tuple(r[c] for c in columns) for r in source.execute(f"SELECT * FROM {table}")]
            with db.cursor() as cursor:
                cursor.executemany(statement, rows)
            counts[table] = len(rows)

        copy(
            "metadata",
            "INSERT INTO metadata (key, value) VALUES (%s, %s) ON CONFLICT DO NOTHING",
            ("key", "value"),
        )
        copy(
            "statements",
            "INSERT INTO statements (period_end, period_start, row_json, pdf, sha256)"
            " VALUES (%s, %s, %s, %s, %s) ON CONFLICT DO NOTHING",
            ("end", "start", "row_json", "pdf", "sha256"),
        )
        copy(
            "events",
            "INSERT INTO events (id, start_date, end_date, title, category, notes, updated_at)"
            " VALUES (%s, %s, %s, %s, %s, %s, %s) ON CONFLICT DO NOTHING",
            ("id", "start", "end", "title", "category", "notes", "updated_at"),
        )
        copy(
            "weather",
            "INSERT INTO weather (location_key, day, mean, low, high, fetched_at)"
            " VALUES (%s, %s, %s, %s, %s, %s) ON CONFLICT DO NOTHING",
            ("location_key", "day", "mean", "low", "high", "fetched_at"),
        )
    db.execute(
        "SELECT setval(pg_get_serial_sequence('events', 'id'), COALESCE(MAX(id), 1), MAX(id) IS NOT NULL)"
        " FROM events"
    )
    stamp = dict(at=datetime.now(UTC).isoformat(), source=path.name, rows=counts)
    db.execute(
        "INSERT INTO metadata (key, value) VALUES (%s, %s)", (LEGACY_FLAG, json.dumps(stamp))
    )
    logging.info("Imported legacy SQLite data into PostgreSQL: %s", counts)
    return counts
